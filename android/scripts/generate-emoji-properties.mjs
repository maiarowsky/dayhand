#!/usr/bin/env node
// Keep the pure Kotlin validator aligned with the backend's ECMAScript Unicode properties.
import { writeFileSync } from 'node:fs';
const output = new URL('../app/src/main/java/dev/helm/planner/domain/EmojiProperties.kt', import.meta.url);
function ranges(property) {
  const regex = new RegExp(`\\p{${property}}`, 'u');
  const out = []; let start = null; let end = null;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (regex.test(String.fromCodePoint(cp))) { if (start === null) start = cp; end = cp; }
    else if (start !== null) { out.push([start, end]); start = null; }
  }
  if (start !== null) out.push([start, end]);
  return out.map(([a,b]) => a === b ? `cp == 0x${a.toString(16).toUpperCase()}` : `cp in 0x${a.toString(16).toUpperCase()}..0x${b.toString(16).toUpperCase()}`);
}
const methods = [['pictographic','Extended_Pictographic'],['modifierBase','Emoji_Modifier_Base']].map(([name,property])=>
  `    fun ${name}(cp: Int): Boolean =\n`+ranges(property).map((range,i)=>`        ${i ? '|| ' : ''}${range}`).join('\n'));
writeFileSync(output, `package dev.helm.planner.domain\n\n// Generated by android/scripts/generate-emoji-properties.mjs (Node Unicode ${process.versions.unicode}).\ninternal object EmojiProperties {\n${methods.join('\n\n')}\n}\n`);
