// Writes convex/lib/outputSchemas.ts from docs/schemas, the one contract of
// the results for MCP, the REST API and hlm: npm run schemas
// Each schema becomes a definition named after its file (task.schema.json ->
// "task") and its references point at those definitions ("#/$defs/task"),
// so a tool's outputSchema is self-contained: clients never fetch a URL.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const SCHEMAS_DIR = new URL("../../docs/schemas/", import.meta.url);
const OUTPUT = new URL("../convex/lib/outputSchemas.ts", import.meta.url);

// The tool results (and the tool error), the REST API's own results and its
// problem details (lib/openapi.ts), and what they reference.
const ROOTS = [
  "task", "task-list", "today", "board", "task-detail", "complete", "set-now", "export", "settings", "tool-error",
  "problem", "api-key-list", "api-key-created", "api-key-revoke",
  "webhook-list", "webhook-one", "webhook-created", "webhook-delete", "webhook-test", "webhook-delivery-list", "webhook-event",
  "import-result",
];

const nameOf = (file) => file.replace(/\.schema\.json$/, "");

function rewrite(node) {
  if (Array.isArray(node)) return node.map(rewrite);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "$schema" || key === "$id") continue;
    out[key] = key === "$ref" && typeof value === "string" ? `#/$defs/${nameOf(value)}` : rewrite(value);
  }
  return out;
}

export function buildDefinitions() {
  const files = new Set(readdirSync(SCHEMAS_DIR).filter((f) => f.endsWith(".schema.json")));
  const defs = {};
  const pending = [...ROOTS];
  while (pending.length) {
    const name = pending.shift();
    if (defs[name]) continue;
    const file = `${name}.schema.json`;
    if (!files.has(file)) throw new Error(`docs/schemas/${file} does not exist`);
    defs[name] = rewrite(JSON.parse(readFileSync(new URL(file, SCHEMAS_DIR), "utf8")));
    for (const match of JSON.stringify(defs[name]).matchAll(/"#\/\$defs\/([\w-]+)"/g)) pending.push(match[1]);
  }
  return Object.fromEntries(Object.keys(defs).sort().map((name) => [name, defs[name]]));
}

export function renderModule(defs = buildDefinitions()) {
  return [
    "// Generated by scripts/gen-output-schemas.mjs from docs/schemas; do not edit.",
    "// Run `npm run schemas` after changing a schema there.",
    "",
    `export const SCHEMA_DEFS: Record<string, Record<string, unknown>> = ${JSON.stringify(defs, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(OUTPUT, renderModule());
